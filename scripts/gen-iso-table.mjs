/**
 * Generates src/model/iso-table.ts — the bridge between the alpha-2 codes a
 * flag emoji encodes and the ISO 3166-1 *numeric* ids world-atlas keys its
 * geometries by.
 *
 * Run: node scripts/gen-iso-table.mjs
 *
 * The mapping is derived, not hand-written: every alpha-2 code the runtime
 * knows is resolved to its English name via Intl.DisplayNames and matched
 * against the atlas feature names. ATLAS_NAME_OVERRIDES covers the 21
 * features Natural Earth spells its own way; anything still unmatched has no
 * geometry at 110m resolution and is deliberately absent.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const ATLAS = 'public/geo/countries-110m.json'
const OUT = 'src/model/iso-table.ts'

/** Natural Earth's spelling → ISO alpha-2. Reviewed by hand; see header. */
const ATLAS_NAME_OVERRIDES = {
  'W. Sahara': 'EH',
  'United States of America': 'US',
  'Dem. Rep. Congo': 'CD',
  'Dominican Rep.': 'DO',
  'Falkland Is.': 'FK',
  'Fr. S. Antarctic Lands': 'TF',
  "Côte d'Ivoire": 'CI',
  'Central African Rep.': 'CF',
  Congo: 'CG',
  'Eq. Guinea': 'GQ',
  eSwatini: 'SZ',
  Palestine: 'PS',
  Myanmar: 'MM',
  Turkey: 'TR',
  'Solomon Is.': 'SB',
  'Bosnia and Herz.': 'BA',
  Macedonia: 'MK',
  'Trinidad and Tobago': 'TT',
  'S. Sudan': 'SS',
  // N. Cyprus and Somaliland are atlas features with no ISO 3166-1 code.
  // They stay unmapped: a node cannot carry a flag for a code that does not
  // exist, so nothing can ever resolve to them.
}

const atlas = JSON.parse(readFileSync(ATLAS, 'utf8'))
const geometries = atlas.objects.countries.geometries

const display = new Intl.DisplayNames(['en'], { type: 'region' })
const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('')

/** English name → alpha-2, for every code this runtime knows. */
const nameToAlpha2 = new Map()
for (const a of letters) {
  for (const b of letters) {
    const code = a + b
    let name
    try {
      name = display.of(code)
    } catch {
      continue
    }
    if (name && name !== code) nameToAlpha2.set(name, code)
  }
}

const table = {}
const unmatched = []
const idless = []
for (const g of geometries) {
  const atlasName = g.properties.name
  // Natural Earth carries a few features with no ISO numeric id — Kosovo,
  // N. Cyprus, Somaliland. There is nothing to key them by, so they are not
  // addressable and must not enter the table as the string "undefined".
  if (g.id === undefined) {
    idless.push(atlasName)
    continue
  }
  const alpha2 = ATLAS_NAME_OVERRIDES[atlasName] ?? nameToAlpha2.get(atlasName)
  if (!alpha2) {
    unmatched.push(atlasName)
    continue
  }
  table[alpha2] = String(g.id)
}

const entries = Object.entries(table).sort(([a], [b]) => a.localeCompare(b))

const body = entries.map(([alpha2, numeric]) => `  ${alpha2}: '${numeric}',`).join('\n')

writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/gen-iso-table.mjs — do not edit by hand.
 *
 * ISO 3166-1 alpha-2 (what a flag emoji encodes) → ISO 3166-1 numeric (what
 * world-atlas keys its country geometries by). Codes absent here have no
 * geometry at 110m resolution.
 */
export const ALPHA2_TO_NUMERIC: Readonly<Record<string, string>> = {
${body}
}

/** ${entries.length} of ${geometries.length} atlas features are addressable by alpha-2. */
export const ATLAS_FEATURE_COUNT = ${geometries.length}
`,
)

console.error(`wrote ${OUT}: ${entries.length}/${geometries.length} features mapped`)
if (unmatched.length) console.error(`unmapped atlas features: ${unmatched.join(', ')}`)
if (idless.length) console.error(`atlas features with no ISO numeric id: ${idless.join(', ')}`)
